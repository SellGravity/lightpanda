var camel_filtered: [camel_entries.len][]const u8 = undefined;
var camel_len: usize = 0;
var camel_for: ?u32 = null;

pub fn camelNames(major: u32) []const []const u8 {
    if (camel_for != major) {
        var n: usize = 0;
        for (camel_entries) |e| {
            if (major == 0 or e.since <= major) {
                camel_filtered[n] = e.name;
                n += 1;
            }
        }
        camel_len = n;
        camel_for = major;
    }
    return camel_filtered[0..camel_len];
}
