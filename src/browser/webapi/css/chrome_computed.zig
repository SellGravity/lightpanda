var filtered: [entries.len][]const u8 = undefined;
var filtered_len: usize = 0;
var filtered_for: ?u32 = null;

/// The names Chrome `major` lists, in Chrome's order. The persona is process
/// global, so the filtered list is computed once.
pub fn names(major: u32) []const []const u8 {
    if (filtered_for != major) {
        var n: usize = 0;
        for (entries) |e| {
            if (major == 0 or e.since <= major) {
                filtered[n] = e.name;
                n += 1;
            }
        }
        filtered_len = n;
        filtered_for = major;
    }
    return filtered[0..filtered_len];
}

